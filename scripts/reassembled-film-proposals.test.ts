import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import Database from 'better-sqlite3';
import { proposeFilmContent } from '../lib/final-edit/reassembled/proposals.ts';
import { createFinalEditWorkspace } from '../lib/final-edit/workspace.ts';

const fixture = JSON.parse(fs.readFileSync(process.env.FILM_CONTENT_FIXTURE!, 'utf8'));
assert.ok(fixture.root.includes('2026-10-19-complete') && fixture.root.includes('reassembled-P1-'));
process.env.CREATIVE_STUDIO_DATA_ROOT = fixture.root;
const db = new Database(path.join(fixture.root, 'data/workbench.db'));
const forbidden = async (): Promise<never> => { throw new Error('Providers forbidden'); };
const workspace = createFinalEditWorkspace({ db, storageRoot: path.join(fixture.root, 'storage'), probeVideo: forbidden, analyzeVideo: forbidden, synthesize: forbidden });
const load = () => workspace.load(fixture.groupId);
const before = load();
const content = structuredClone(before.reassembled!.content);
assert.ok(content.decoration.template !== 'classic');
content.decoration.packaging.varsOverrides.title = '待人工采用的提案';
const input = { requestId: randomUUID(), expectedRevision: before.variants[0].revision, summary: '只修改主标题', content };
const result = proposeFilmContent(db, fixture.groupId, input, 'agent');
assert.deepEqual(load().variants, before.variants, 'proposal cannot change current edit');
assert.deepEqual(load().reassembled!.content, before.reassembled!.content);
assert.deepEqual(proposeFilmContent(db, fixture.groupId, input, 'agent'), result);
assert.throws(() => proposeFilmContent(db, fixture.groupId, { ...input, summary: 'changed' }, 'agent'), { code: 'request_conflict' });
assert.throws(() => proposeFilmContent(db, fixture.groupId, input, 'human'), { code: 'request_conflict' });
assert.throws(() => proposeFilmContent(db, fixture.groupId, { ...input, requestId: randomUUID(), expectedRevision: -1 }, 'agent'), { code: 'revision_conflict' });
const invalid = structuredClone(input); invalid.requestId = randomUUID(); Object.assign(invalid.content.music, { file: 'foreign' });
assert.throws(() => proposeFilmContent(db, fixture.groupId, invalid, 'agent'), { code: 'film_content_invalid' });
const envelope = { scope: 'variant' as const, variantId: before.variants[0].id, expectedRevision: before.variants[0].revision, type: 'set_film_content' as const };
// A separate human save makes the proposal stale, including attempts to pass a refreshed revision.
workspace.apply({ ...envelope, content: before.reassembled!.content });
assert.throws(() => workspace.apply({ ...envelope, expectedRevision: load().variants[0].revision, proposalId: result.id, content }), { code: 'proposal_stale' });
assert.deepEqual(load().reassembled!.content, before.reassembled!.content);
const fresh = { ...input, requestId: randomUUID(), expectedRevision: load().variants[0].revision };
const candidate = proposeFilmContent(db, fixture.groupId, fresh, 'agent');
workspace.apply({ ...envelope, expectedRevision: fresh.expectedRevision, proposalId: candidate.id, content });
assert.deepEqual(load().reassembled!.content, content);
assert.deepEqual(load().variants[0].timeline.clips, before.variants[0].timeline.clips);
assert.equal(load().reassembled!.proposals.find(p => p.id === candidate.id)!.status, 'applied');
assert.throws(() => workspace.apply({ ...envelope, expectedRevision: load().variants[0].revision, proposalId: candidate.id, content }), { code: 'proposal_not_ready' });
assert.deepEqual(proposeFilmContent(db, fixture.groupId, fresh, 'agent'), candidate, 'late retry cannot recreate or reapply');
db.close();
console.log('PASS proposal-only creation, idempotency, ownership, invalid content, stale baseline protection, explicit adoption and replay');
