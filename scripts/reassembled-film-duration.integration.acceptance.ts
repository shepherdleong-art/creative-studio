// Fresh isolated FILM_DURATION_FIXTURE; FILM_DURATION_RENDER=1 exercises the actual fixed renderer.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import Database from 'better-sqlite3';
import { createFinalEditWorkspace } from '../lib/final-edit/workspace.ts';
import { filmBinding } from '../lib/final-edit/reassembled/store.ts';
import { enqueueFilmRender, executeFilmJob } from '../lib/final-edit/reassembled/jobs.ts';
import { sha256 } from '../lib/film-render/files.ts';

const fixture = JSON.parse(fs.readFileSync(process.env.FILM_DURATION_FIXTURE!, 'utf8'));
assert.ok(fixture.root.includes('2026-10-19-film-duration') && fixture.root.includes('reassembled-P1-'));
process.env.CREATIVE_STUDIO_DATA_ROOT = fixture.root;
process.env.CREATIVE_STUDIO_PACKAGING_DIR = path.resolve('packaging');
const db = new Database(path.join(fixture.root, 'data/workbench.db'));
db.pragma('foreign_keys = ON');
const storageRoot = path.join(fixture.root, 'storage');
const forbidden = async (): Promise<never> => { throw new Error('Provider calls forbidden'); };
const workspace = createFinalEditWorkspace({ db, storageRoot, probeVideo: forbidden, analyzeVideo: forbidden, synthesize: forbidden });
const load = () => workspace.load(fixture.groupId);
const initial = load(), binding = filmBinding(db, fixture.groupId)!;
const variantId = initial.variants[0].id;
const supplierRows = JSON.stringify(db.prepare('SELECT * FROM video_jobs ORDER BY id').all());
const oldHashes = fs.readdirSync(fixture.delivery).filter((file: string) => /\.(mp4|jpg)$/.test(file)).map((file: string) => [file, sha256(path.join(fixture.delivery, file))]);
const content = structuredClone(initial.reassembled!.content);
content.subtitles[0].text = '时长变化保留人工字幕'; content.music.gainDb -= 2;
workspace.apply({ scope: 'variant', type: 'set_film_content', variantId, expectedRevision: initial.variants[0].revision, content });
const before = load().variants[0], first = before.timeline.clips[0];
const command = { scope: 'variant' as const, type: 'set_film_clip_duration' as const, variantId, expectedRevision: before.revision, clipId: first.id, durationFrames: first.timelineOutFrame - first.timelineInFrame + 24 };
workspace.apply(command);
const after = load().variants[0];
assert.equal(after.timeline.bodyFrames, before.timeline.bodyFrames + 24);
assert.deepEqual(after.timeline.clips.slice(1), before.timeline.clips.slice(1).map(c => ({ ...c, timelineInFrame: c.timelineInFrame + 24, timelineOutFrame: c.timelineOutFrame + 24 })));
assert.deepEqual(after.timeline.filmContent, content);
assert.equal(load().totalDurationUs, Math.round((after.timeline.bodyFrames + 20) / 24 * 1e6));
assert.throws(() => workspace.apply(command), { code: 'revision_conflict' });
assert.throws(() => workspace.apply({ ...command, expectedRevision: after.revision, durationFrames: 10000 }), /素材/);
assert.deepEqual(load().variants[0], after);
workspace.apply({ ...command, expectedRevision: after.revision, durationFrames: command.durationFrames - 36 });
const shorter = load().variants[0];
assert.equal(shorter.timeline.bodyFrames, before.timeline.bodyFrames - 12);
assert.deepEqual(shorter.timeline.filmContent, content);
workspace.apply({ scope: 'variant', type: 'restore_revision', variantId, expectedRevision: shorter.revision, revision: before.revision });
assert.deepEqual(load().variants[0].timeline, before.timeline);
workspace.apply({ scope: 'variant', type: 'restore_revision', variantId, expectedRevision: load().variants[0].revision, revision: after.revision });
assert.deepEqual(load().variants[0].timeline, after.timeline);
assert.equal(filmBinding(db, fixture.groupId)!.specJson, binding.specJson);
assert.equal(filmBinding(db, fixture.groupId)!.inputHashesJson, binding.inputHashesJson);
assert.equal(JSON.stringify(db.prepare('SELECT * FROM video_jobs ORDER BY id').all()), supplierRows);
const current = load();
const job = enqueueFilmRender(db, { groupId: fixture.groupId, variantId, expectedGroupRevision: current.revision, expectedVariantRevision: current.variants[0].revision }, 'preview');
const row = db.prepare('SELECT id,groupId,inputSnapshotJson FROM final_edit_jobs WHERE id=?').get(job.id) as { id: string; groupId: string; inputSnapshotJson: string };
const snapshot = JSON.parse(row.inputSnapshotJson);
assert.equal(snapshot.spec.canvas.frames, before.timeline.bodyFrames + 44);
assert.deepEqual(snapshot.spec.subtitles, content.subtitles);
let output;
if (process.env.FILM_DURATION_RENDER === '1') {
  db.prepare("UPDATE final_edit_jobs SET status='running' WHERE id=?").run(job.id);
  await executeFilmJob(db, storageRoot, row, new AbortController().signal);
  const result = db.prepare('SELECT status,outputJson FROM final_edit_jobs WHERE id=?').get(job.id) as { status: string; outputJson: string };
  assert.equal(result.status, 'succeeded'); output = JSON.parse(result.outputJson);
}
for (const [file, hash] of oldHashes) assert.equal(sha256(path.join(fixture.delivery, file)), hash);
fs.writeFileSync(path.join(fixture.root, 'duration-result.json'), JSON.stringify({ ok: true, paidCalls: 0, manualContentPreserved: true, otherSourceRangesUnchanged: true, restored: true, snapshotFrames: snapshot.spec.canvas.frames, rendered: !!output, output }, null, 2));
db.close();
console.log('PASS duration persistence, stale/unsafe edits rejected, shorten/extend/restore, frozen render and old delivery');
