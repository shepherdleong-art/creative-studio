import assert from 'node:assert/strict';
import ExcelJS from 'exceljs';
import { readFormulaWorkbook } from '../lib/live-mixcut/formula/workbook.ts';

const workbook = new ExcelJS.Workbook();
const sheet = workbook.addWorksheet('脚本');
sheet.addRow(['序号', '平台', '镜头数', '预估时长(s)', '画面分镜（逻辑镜号组合）', '脚本文案']);
sheet.addRow([12, '抖音', 3, 16, '【G1】【VO1】【G1】', '第一句。\n第二句。']);
const bytes = Buffer.from(await workbook.xlsx.writeBuffer());
const result = await readFormulaWorkbook(bytes, 'scripts');
assert.equal(result.rows.length, 1);
assert.deepEqual(result.rows[0].codes, ['G1', 'VO1', 'G1']);
assert.equal(result.rows[0].scriptNumber, '12');
assert.equal(result.rows[0].source.row, 2);
assert.equal(result.rows[0].bodyText, '第一句。\n第二句。');
assert.deepEqual(result.issues, []);
// 计算值即使已有缓存，也不能被当成权威素材编号或脚本内容。
sheet.addRow([13, '抖音', 1, 16, { formula: '"G1"', result: 'G1' }, '不能接受缓存公式']);
sheet.addRow([12, '抖音', 1, 16, 'G1', '重复序号']);
sheet.addRow([14, '抖音', 1, 0, 'G1', '无效时长']);
const invalid = await readFormulaWorkbook(Buffer.from(await workbook.xlsx.writeBuffer()), 'scripts');
assert.equal(invalid.rowCount, 4);
assert.equal(invalid.rows.length, 0, '重复序号的两行都需处理，不任取第一行');
assert.equal(invalid.issues.length, 4);
assert(invalid.issues.some(issue => /计算.*转.*值/.test(issue.message)));
assert(invalid.issues.some(issue => /时长/.test(issue.message)));
const duplicateWorkbook = new ExcelJS.Workbook();
const duplicateSheet = duplicateWorkbook.addWorksheet('重复但另一行有错');
duplicateSheet.addRow(sheet.getRow(1).values);
duplicateSheet.addRow([1, '抖音', 1, 16, 'G1', '有效内容']);
duplicateSheet.addRow([1, '抖音', 1, 0, 'G1', '另一行时长错误']);
const duplicateResult = await readFormulaWorkbook(Buffer.from(await duplicateWorkbook.xlsx.writeBuffer()), 'scripts');
assert.equal(duplicateResult.rows.length, 0, '编号冲突不能因为另一行有错而忽略');
assert.equal(duplicateResult.issues.length, 2);

const materials = new ExcelJS.Workbook();
const materialSheet = materials.addWorksheet('素材');
materialSheet.addRow(['逻辑编号', '画面描述', '口播/旁白(可选)']);
materialSheet.addRow(['S76', '3cm 金属脚，扫地机器人通过', '']);
const materialResult = await readFormulaWorkbook(Buffer.from(await materials.xlsx.writeBuffer()), 'materials');
assert.equal(materialResult.rows[0].logicalCode, 'S76');
assert.equal(materialResult.rows[0].fields['画面描述'], '3cm 金属脚，扫地机器人通过');
assert.equal(materialResult.rows[0].source.cells['逻辑编号'], 'A2');
await assert.rejects(() => readFormulaWorkbook(Buffer.alloc(10 * 1024 * 1024 + 1), 'scripts'), /10 MiB/);
await assert.rejects(() => readFormulaWorkbook(Buffer.from('不是工作簿'), 'scripts'), /XLSX/);
const oversized = new ExcelJS.Workbook();
oversized.addWorksheet('超限').getCell('AZ10001').value = '不可先展开单元格再检查';
await assert.rejects(async () => readFormulaWorkbook(Buffer.from(await oversized.xlsx.writeBuffer()), 'scripts'), /10,000 行或 50 列/);
const compressedBudget = Buffer.from(bytes);
const centralHeader = compressedBudget.indexOf(Buffer.from([0x50, 0x4b, 0x01, 0x02]));
assert(centralHeader >= 0);
compressedBudget.writeUInt32LE(101 * 1024 * 1024, centralHeader + 24);
await assert.rejects(() => readFormulaWorkbook(compressedBudget, 'scripts'), /100 MiB/);
console.log('formula-workbook: 脚本与来源读取通过');
