// Fresh isolated FILM_EXTERNAL_FIXTURE; real local upload/probe, no suppliers.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import Database from 'better-sqlite3';
import { probeVideoMedia } from '../lib/ffmpeg.ts';
import { createFinalEditWorkspace } from '../lib/final-edit/workspace.ts';
import { importShotSetExternalAssetsFromFormData } from '../lib/final-edit/material-import-http.ts';
import { applyFilmRework, readFilmRework } from '../lib/final-edit/reassembled/rework.ts';
import { filmBinding } from '../lib/final-edit/reassembled/store.ts';
import { enqueueFilmRender, executeFilmJob } from '../lib/final-edit/reassembled/jobs.ts';
import type { RegisteredCandidate } from '../lib/final-edit/reassembled/types.ts';

const fixture = JSON.parse(fs.readFileSync(process.env.FILM_EXTERNAL_FIXTURE!, 'utf8'));
assert.ok(fixture.root.includes('2026-10-19-film-editing') && fixture.root.includes('reassembled-P1-'));
process.env.CREATIVE_STUDIO_DATA_ROOT = fixture.root;
process.env.CREATIVE_STUDIO_PACKAGING_DIR = path.resolve('packaging');
const db = new Database(path.join(fixture.root, 'data/workbench.db'));
db.pragma('foreign_keys = ON');
const storageRoot = path.join(fixture.root, 'storage');
const forbidden = async (): Promise<never> => { throw new Error('Provider calls forbidden'); };
const workspace = createFinalEditWorkspace({ db, storageRoot, probeVideo: ({ filePath }) => probeVideoMedia(filePath), analyzeVideo: forbidden, synthesize: forbidden });
const load = () => workspace.load(fixture.groupId);
const binding = filmBinding(db, fixture.groupId)!;
const content = structuredClone(load().reassembled!.content); content.subtitles[0].text = '外部视频保留人工字幕'; content.music.gainDb -= 2;
workspace.apply({ scope: 'variant', type: 'set_film_content', variantId: binding.variantId, expectedRevision: load().variants[0].revision, content });
const before = load();
const clip = before.variants[0].timeline.clips[0];
const jobsBefore = db.prepare('SELECT * FROM video_jobs ORDER BY rowid').all();
const source = path.resolve(process.env.FILM_EXTERNAL_SOURCE!);
assert.ok(source.includes('2026-10-19-film-editing') && source.endsWith('motion.mp4'));
const form = new FormData(); form.append('file', new File([fs.readFileSync(source)], '用户 合成视频.mp4', { type: 'video/mp4' }));
const uploaded = await importShotSetExternalAssetsFromFormData(new Request('http://127.0.0.1/upload', { method: 'POST', body: form }), files => workspace.importShotSetExternalAssets({ projectId: binding.projectId, shotSetId: binding.shotSetId, files }));
assert.deepEqual(uploaded.errors, []); assert.equal(uploaded.assets.length, 1);
const asset = uploaded.assets[0];
assert.deepEqual(load().variants, before.variants, 'upload does not edit timeline');
const row = db.prepare('SELECT relativePath FROM final_edit_external_assets WHERE id=?').get(asset.id) as { relativePath: string };
const videoFile = path.join(storageRoot, row.relativePath);
const view = () => readFilmRework(db, fixture.groupId, clip.id);
const request = () => ({ type: 'register_external' as const, requestId: randomUUID(), expectedRevision: view().revision, externalAssetId: asset.id, approvedRangeSec: [0, 12] as [number, number] });
const apply = (command = request()) => applyFilmRework(db, storageRoot, fixture.groupId, clip.id, command, 'agent');
db.prepare("UPDATE final_edit_external_assets SET projectId='foreign' WHERE id=?").run(asset.id);
await assert.rejects(apply(), /当前分镜组/);
db.prepare('UPDATE final_edit_external_assets SET projectId=? WHERE id=?').run(binding.projectId, asset.id);
const originalBytes = fs.readFileSync(videoFile); fs.appendFileSync(videoFile, 'changed');
await assert.rejects(apply(), /文件已变化/); fs.writeFileSync(videoFile, originalBytes);
await assert.rejects(apply({ ...request(), approvedRangeSec: [0, 99] }), /实际视频时长/);
const racing = apply();
db.prepare("UPDATE final_edit_external_assets SET status='failed' WHERE id=?").run(asset.id);
await assert.rejects(racing, { code: 'revision_conflict' });
db.prepare("UPDATE final_edit_external_assets SET status='ready' WHERE id=?").run(asset.id);
assert.equal(filmBinding(db, fixture.groupId)!.candidatesJson, binding.candidatesJson);
assert.deepEqual(load().variants, before.variants);
const command = request(); const result = await apply(command);
assert.deepEqual(await apply(command), result, 'replay returns original receipt');
assert.throws(() => workspace.deleteShotSetExternalAsset({ projectId: binding.projectId, shotSetId: binding.shotSetId, assetId: asset.id }), { code: 'external_asset_in_use' });
const candidate = (JSON.parse(filmBinding(db, fixture.groupId)!.candidatesJson) as RegisteredCandidate[]).find(candidate => candidate.externalAssetId === asset.id)!;
assert.ok(candidate);
const visible = load().assets.find(item => item.videoJobId === candidate.videoJobId)!;
assert.equal(visible.source, 'external'); assert.equal(visible.fingerprint, candidate.fingerprint);
assert.match(visible.previewUrl!, /external-assets/);
assert.deepEqual(load().variants, before.variants, 'candidate registration does not edit timeline');
const replacement = { scope: 'variant' as const, type: 'replace_clip' as const, variantId: binding.variantId, expectedRevision: before.variants[0].revision, clipId: clip.id, videoJobId: candidate.videoJobId, sourceFingerprint: candidate.fingerprint, sourceInFrame: 0, sourceOutFrame: clip.sourceOutFrame - clip.sourceInFrame };
assert.throws(() => workspace.apply({ ...replacement, clipId: before.variants[0].timeline.clips[1].id }), { code: 'film_edit_unsupported' });
workspace.apply(replacement);
const after = load();
assert.deepEqual(after.variants[0].timeline.clips.slice(1), before.variants[0].timeline.clips.slice(1));
assert.deepEqual(after.variants[0].timeline.filmContent, content);
assert.deepEqual(db.prepare('SELECT * FROM video_jobs ORDER BY rowid').all(), jobsBefore, 'no fake supplier job');
assert.equal(filmBinding(db, fixture.groupId)!.specJson, binding.specJson);
workspace.apply({ scope: 'variant', type: 'restore_revision', variantId: binding.variantId, expectedRevision: after.variants[0].revision, revision: before.variants[0].revision });
assert.deepEqual(load().variants[0].timeline, before.variants[0].timeline);
workspace.apply({ scope: 'variant', type: 'restore_revision', variantId: binding.variantId, expectedRevision: load().variants[0].revision, revision: after.variants[0].revision });
const current = load();
const job = enqueueFilmRender(db, { groupId: fixture.groupId, variantId: binding.variantId, expectedGroupRevision: current.revision, expectedVariantRevision: current.variants[0].revision }, 'preview');
const frozen = db.prepare('SELECT id,groupId,inputSnapshotJson FROM final_edit_jobs WHERE id=?').get(job.id) as { id: string; groupId: string; inputSnapshotJson: string };
assert.equal(JSON.parse(frozen.inputSnapshotJson).spec.shots[0].file, candidate.file);
let output;
if (process.env.FILM_EXTERNAL_RENDER === '1') {
  db.prepare("UPDATE final_edit_jobs SET status='running' WHERE id=?").run(job.id);
  await executeFilmJob(db, storageRoot, frozen, new AbortController().signal);
  const rendered = db.prepare('SELECT status,outputJson FROM final_edit_jobs WHERE id=?').get(job.id) as { status: string; outputJson: string };
  assert.equal(rendered.status, 'succeeded'); output = JSON.parse(rendered.outputJson);
}
fs.writeFileSync(path.join(fixture.root, 'external-result.json'), JSON.stringify({ ok: true, paidCalls: 0, assetId: asset.id, manualContentPreserved: true, otherShotsUnchanged: true, noSupplierJobs: true, deletionProtected: true, restored: true, rendered: !!output, output }, null, 2));
db.close();
console.log('PASS actual multipart import, candidate/source/CAS guards, immutable copy, explicit adoption and history restore');
