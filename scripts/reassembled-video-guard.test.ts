import assert from 'node:assert/strict';
import Database from 'better-sqlite3';
import { isReassembledShotSet, requiresReassembledUpstreamRework, requiresReassembledImageRework } from '../lib/reassembled-shot-guard.ts';

const db = new Database(':memory:');
assert.equal(requiresReassembledUpstreamRework(db, 'ordinary'), false);
db.exec(`CREATE TABLE final_edit_film_production_items (shotSetId TEXT, registryJson TEXT);
  CREATE TABLE final_edit_film_bindings (shotSetId TEXT, variantId TEXT, id TEXT);
  CREATE TABLE final_edit_film_reworks (bindingId TEXT, jobId TEXT, kind TEXT);
  CREATE TABLE final_edit_variants (id TEXT, timelineJson TEXT);
  INSERT INTO final_edit_film_production_items VALUES ('production', '{"jobs":{"image":"pending-image"}}'), ('completed', '{"jobs":{"image":"completed-image"}}');
  INSERT INTO final_edit_film_bindings VALUES ('completed', 'v1', 'b1'), ('legacy', 'v2', 'b2');
  INSERT INTO final_edit_film_reworks VALUES ('b1', 'p2-adopted-image', 'generate_image'), ('b2', 'p2-legacy-image', 'generate_image');
  INSERT INTO final_edit_variants VALUES ('v1', '{"importedFilmEditor":"mixcut"}'), ('v2', '{}');`);
assert.equal(requiresReassembledUpstreamRework(db, 'ordinary'), false);
assert.equal(requiresReassembledUpstreamRework(db, 'production'), true);
assert.equal(requiresReassembledUpstreamRework(db, 'legacy'), true);
assert.equal(requiresReassembledUpstreamRework(db, 'completed'), false);
assert.equal(isReassembledShotSet(db, 'completed'), true, 'Destructive shot operations remain protected');
assert.equal(requiresReassembledImageRework(db, 'ordinary-image'), false);
assert.equal(requiresReassembledImageRework(db, 'completed-image'), false);
assert.equal(requiresReassembledImageRework(db, 'p2-adopted-image'), false);
assert.equal(requiresReassembledImageRework(db, 'pending-image'), true);
assert.equal(requiresReassembledImageRework(db, 'p2-legacy-image'), true);
db.prepare('UPDATE final_edit_variants SET timelineJson=? WHERE id=?').run('{}', 'v1');
assert.equal(requiresReassembledUpstreamRework(db, 'completed'), true);
assert.equal(requiresReassembledImageRework(db, 'completed-image'), true);
db.close();
console.log('PASS: ordinary/adopted video creation, incomplete/legacy guard, destructive protection');
